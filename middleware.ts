import { NextResponse } from 'next/server'
import type { NextRequest } from 'next/server'

export function middleware(request: NextRequest) {
  const path = request.nextUrl.pathname

  // Define the protected paths based on roles
  const isCookRoute = path.startsWith('/cook')
  const isDispatchRoute = path.startsWith('/dispatch')
  const isOwnerRoute = path.startsWith('/owner')

  // If it's not a protected route, let them through (e.g., to the /login page)
  if (!isCookRoute && !isDispatchRoute && !isOwnerRoute) {
    return NextResponse.next()
  }

  // Check for the daily PIN cookie generated by the owner
  const pinCookie = request.cookies.get('kitchen_pin')?.value

  // If no PIN is found in the browser, instantly redirect to the login screen
  if (!pinCookie) {
    return NextResponse.redirect(new URL('/login', request.url))
  }

  // If PIN exists, allow access to the requested role view. 
  // (Specific PIN-to-Role validation logic will happen at the /login API route).
  return NextResponse.next()
}

// Optimize middleware to only run on specific role paths
export const config = {
  matcher: ['/cook/:path*', '/dispatch/:path*', '/owner/:path*'],
}
