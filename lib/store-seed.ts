export function buildPerKitchenSeedInventory(): InventoryItem[] {
  const rows: InventoryItem[] = [];

  for (const kitchen of KITCHENS_DB) {
    const kitchenOverrides = PER_KITCHEN_STOCK_OVERRIDES[kitchen.id] ?? {};
    for (const ingredient of INVENTORY_DB) {
      const override = kitchenOverrides[ingredient.id];
      rows.push({
        ...ingredient,
        id: ingredient.id,
        ingredientId: ingredient.id,
        kitchenId: kitchen.id,
        currentStock:
          override?.currentStock ?? ingredient.currentStock,
        reorderThreshold:
          override?.reorderThreshold ?? ingredient.reorderThreshold,
      });
    }
  }

  return rows;
}

